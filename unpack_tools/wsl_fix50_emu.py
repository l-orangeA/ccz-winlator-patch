NL = chr(10)
p2 = '/root/wine0905/dlls/ntdll/unix/signal_x86_64.c'
s2 = open(p2, encoding='utf-8', errors='replace').read()
if 'HWBP_EMU' in s2:
    print('already')
else:
    old = NL.join([
'                        {   /* HWBP_LEN: report the trap at the next instruction */',
'                          unsigned char *ip = (unsigned char *)RIP_sig(ucontext);',
'                          int len = 1;',
'                          unsigned char op = ip[0];',
'                          if (op == 0x8b || op == 0x89 || op == 0x8a || op == 0x88 ||',
'                              op == 0x8d || op == 0x85 || op == 0x8f || op == 0x03 ||',
'                              op == 0x39 || op == 0x3b || op == 0x01)',
'                          {',
'                              int modrm = ip[1], mod = modrm >> 6, rm = modrm & 7;',
'                              len = 2;',
'                              if (rm == 4 && mod != 3) len += 1;',
'                              if (mod == 0 && rm == 5) len += 4;',
'                              else if (mod == 1) len += 1;',
'                              else if (mod == 2) len += 4;',
'                          }',
'                          else if (op >= 0x50 && op <= 0x5f) len = 1;',
'                          srec.ExceptionAddress = (void *)((ULONG_PTR)ip + len);',
'                        }'])
    new = NL.join([
'                        {   /* HWBP_LEN/EMU: emulate the faulting access, then trap at next insn */',
'                          unsigned char *ip = (unsigned char *)RIP_sig(ucontext);',
'                          int len = 1;',
'                          unsigned char op = ip[0];',
'                          int reg = -1, mod = 0, rm = 0;',
'                          if (op == 0x8b || op == 0x89 || op == 0x8a || op == 0x88 ||',
'                              op == 0x8d || op == 0x85 || op == 0x8f || op == 0x03 ||',
'                              op == 0x39 || op == 0x3b || op == 0x01)',
'                          {',
'                              int modrm = ip[1];',
'                              mod = modrm >> 6; rm = modrm & 7; reg = (modrm >> 3) & 7;',
'                              len = 2;',
'                              if (rm == 4 && mod != 3) len += 1;',
'                              if (mod == 0 && rm == 5) len += 4;',
'                              else if (mod == 1) len += 1;',
'                              else if (mod == 2) len += 4;',
'                          }',
'                          else if (op >= 0x50 && op <= 0x5f) len = 1;',
'                          /* HWBP_EMU: perform the memory access so the guest sees it done */',
'                          if (mod != 3 && (op == 0x8b || op == 0x8a || op == 0x89 || op == 0x88))',
'                          {',
'                              ULONG_PTR a = (ULONG_PTR)siginfo->si_addr;',
'                              if (op == 0x8b)',
'                              {',
'                                  ULONG v = *(ULONG *)a;',
'                                  switch (reg) {',
'                                  case 0: RAX_sig(ucontext) = v; break;',
'                                  case 1: RCX_sig(ucontext) = v; break;',
'                                  case 2: RDX_sig(ucontext) = v; break;',
'                                  case 3: RBX_sig(ucontext) = v; break;',
'                                  case 5: RBP_sig(ucontext) = v; break;',
'                                  case 6: RSI_sig(ucontext) = v; break;',
'                                  case 7: RDI_sig(ucontext) = v; break;',
'                                  default: break;',
'                                  }',
'                              }',
'                              else if (op == 0x8a)',
'                              {',
'                                  ULONG v = *(unsigned char *)a;',
'                                  switch (reg) {',
'                                  case 0: RAX_sig(ucontext) = (RAX_sig(ucontext) & ~0xffu) | v; break;',
'                                  case 1: RCX_sig(ucontext) = (RCX_sig(ucontext) & ~0xffu) | v; break;',
'                                  case 2: RDX_sig(ucontext) = (RDX_sig(ucontext) & ~0xffu) | v; break;',
'                                  case 3: RBX_sig(ucontext) = (RBX_sig(ucontext) & ~0xffu) | v; break;',
'                                  default: break;',
'                                  }',
'                              }',
'                              else if (op == 0x89)',
'                              {',
'                                  ULONG v = 0;',
'                                  switch (reg) {',
'                                  case 0: v = (ULONG)RAX_sig(ucontext); break;',
'                                  case 1: v = (ULONG)RCX_sig(ucontext); break;',
'                                  case 2: v = (ULONG)RDX_sig(ucontext); break;',
'                                  case 3: v = (ULONG)RBX_sig(ucontext); break;',
'                                  case 5: v = (ULONG)RBP_sig(ucontext); break;',
'                                  case 6: v = (ULONG)RSI_sig(ucontext); break;',
'                                  case 7: v = (ULONG)RDI_sig(ucontext); break;',
'                                  default: break;',
'                                  }',
'                                  *(ULONG *)a = v;',
'                              }',
'                              else if (op == 0x88)',
'                              {',
'                                  ULONG v = 0;',
'                                  switch (reg) {',
'                                  case 0: v = (ULONG)RAX_sig(ucontext) & 0xff; break;',
'                                  case 1: v = (ULONG)RCX_sig(ucontext) & 0xff; break;',
'                                  case 2: v = (ULONG)RDX_sig(ucontext) & 0xff; break;',
'                                  case 3: v = (ULONG)RBX_sig(ucontext) & 0xff; break;',
'                                  default: break;',
'                                  }',
'                                  *(unsigned char *)a = (unsigned char)v;',
'                              }',
'                              RIP_sig(ucontext) += len;   /* skip the emulated instruction */',
'                          }',
'                          srec.ExceptionAddress = (void *)((ULONG_PTR)ip + len);',
'                        }'])
    assert old in s2, 'len block'
    s2 = s2.replace(old, new, 1)
    open(p2, 'w', encoding='utf-8', newline=NL).write(s2)
    print('patched HWBP_EMU')
